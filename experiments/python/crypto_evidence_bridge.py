#!/usr/bin/env python3
"""Bind deterministic QoS traces to real AAPA cryptographic evidence.

Every formal E7/E11 case passes through this adapter.  Checkpoints, Merkle or
hash-chain commitments, ML-DSA/Ed25519 signatures, witness receipts, trusted
registry bindings, anchors, and A2 wire MACs are generated by the production
implementation and verified by ``audit_verify.audit_stream``.  The semantic
auditor receives the resulting verifier transcript plus the actual committed
record digests; it never consumes synthetic ``signature_valid`` flags.
"""

from __future__ import annotations

import copy
import hashlib
import json
from dataclasses import dataclass
from typing import Any, Mapping

from aapa_mqtt import Record, create_arm
from audit_verify import anchors_for_generated_evidence, audit_stream, bundle_to_dict, verify_signature
from trusted_registry import registry_for_generated_evidence
from stream_identity import canonical_stream_id


CRYPTO_BRIDGE_SCHEMA_VERSION = "qos-real-crypto-bridge-v1"
FIXED_AUDIT_TIME = 2_000_000_000.0


@dataclass
class CryptoTemplate:
    arm_id: str
    topic: str
    records: list[bytes]
    wire_messages: list[bytes]
    evidence: list[Any]
    registry: Any | None
    anchors: Any | None
    subscriber_verifier_factory: Any


def build_crypto_template(
    arm_id: str,
    *,
    n_records: int,
    checkpoint_interval: int,
    witness_count: int = 3,
) -> CryptoTemplate:
    """Generate one canonical real-crypto source stream for an arm."""

    topic = f"telemetry/audit/{arm_id.lower()}"
    arm = create_arm(
        arm_id,
        topic,
        N=checkpoint_interval,
        witness_count=witness_count,
    )
    for seq in range(1, n_records + 1):
        payload = hashlib.sha256(f"qos-corpus:{arm_id}:{seq}".encode()).digest()[:16]
        arm.add_record(Record.make(seq, topic, payload, ts=1_800_000_000.0 + seq))
    if hasattr(arm, "flush"):
        arm.flush()
    evidence = copy.deepcopy(list(arm.checkpoints))
    records = [record.serialize() for record in arm.records]
    wire_messages = list(arm.wire_messages)
    verifier_factory = arm.new_subscriber_verifier
    if arm_id == "A2":
        registry = None
        anchors = None
    else:
        registry = registry_for_generated_evidence(
            evidence,
            arm_id,
            witness_quorum=2 if arm_id == "A6" else None,
            registry_id=f"qos-corpus-{arm_id.lower()}-registry",
        )
        anchors = anchors_for_generated_evidence(
            evidence,
            include_latest=True,
            observed_at=FIXED_AUDIT_TIME - 1,
            valid_until=FIXED_AUDIT_TIME + 86_400,
            anchor_set_id=f"qos-corpus-{arm_id.lower()}-anchors",
        )
    # Evidence and verifier retain the key material required after the arm is
    # freed; the verifier factory is a bound method and therefore keeps the arm
    # alive for the suite lifetime.  The suite creates only one template/arm.
    return CryptoTemplate(
        arm_id=arm_id,
        topic=topic,
        records=records,
        wire_messages=wire_messages,
        evidence=evidence,
        registry=registry,
        anchors=anchors,
        subscriber_verifier_factory=verifier_factory,
    )


def bind_trace_to_crypto(trace: Mapping[str, Any], template: CryptoTemplate) -> dict[str, Any]:
    """Replace model-only digests with digests of actual Record serializations."""

    bound = copy.deepcopy(dict(trace))
    actual_digest = {
        seq: hashlib.sha256(raw).hexdigest()
        for seq, raw in enumerate(template.records, start=1)
    }
    actual_epoch: dict[int, int] = {}
    for item in template.evidence:
        for seq in range(item.checkpoint.seq_start, item.checkpoint.seq_end + 1):
            actual_epoch[seq] = item.checkpoint.epoch
    if not actual_epoch:
        actual_epoch = {seq: 0 for seq in actual_digest}
    synthetic_publisher = {
        int(event["seq"]): str(event["digest"])
        for event in bound.get("timeline", ())
        if event.get("event") == "publisher_publish"
    }
    for event in bound.get("timeline", ()):
        if "topic" in event and event.get("event") in (
            "publisher_publish", "subscriber_delivery", "checkpoint_created",
            "checkpoint_presented",
        ):
            event["topic"] = template.topic
        # Every stream-bearing event (checkpoints, trusted_latest_anchor,
        # witness_receipt, ...) must reflect the rebound topic under one
        # canonical identity, never a stale base-topic id.
        if "stream_id" in event:
            event["stream_id"] = canonical_stream_id("publisher-001", template.topic)
        if event.get("event") == "publisher_publish":
            event["epoch"] = actual_epoch[int(event["seq"])]
            event["digest"] = actual_digest[int(event["seq"])]
        elif event.get("event") == "broker_accept" and int(event["seq"]) in actual_epoch:
            event["epoch"] = actual_epoch[int(event["seq"])]
        elif event.get("event") == "subscriber_delivery":
            seq = int(event["seq"])
            if seq not in actual_digest:
                continue
            # A replay intentionally retains the source epoch, which is the
            # actual epoch carried by its signed/MAC envelope.
            event["epoch"] = actual_epoch[seq]
            if str(event.get("digest")) == synthetic_publisher.get(seq):
                event["digest"] = actual_digest[seq]
            else:
                event["digest"] = hashlib.sha256(
                    bytes.fromhex(actual_digest[seq]) + str(event.get("digest")).encode()
                ).hexdigest()
    return bound


def _scenario_actions(trace: Mapping[str, Any]) -> set[str]:
    return {
        str(event.get("action"))
        for event in trace.get("timeline", ())
        if event.get("event") == "causal_action"
    }


def _mutated_evidence(
    template: CryptoTemplate,
    actions: set[str],
    *,
    witness_receipt_limit: int | None = None,
) -> list[Any]:
    evidence = copy.deepcopy(template.evidence)
    if "checkpoint_splice" in actions and len(evidence) > 1:
        evidence[1].checkpoint.topic = f"{template.topic}/spliced"
        evidence[1].checkpoint.prev_anchor = b"\xff" * 32
    if "checkpoint_rollback" in actions or "omit_tail_checkpoint" in actions:
        evidence = evidence[:-1]
    if "omit_middle_checkpoint" in actions and len(evidence) > 1:
        evidence = evidence[1:]
    if "withhold_witness_receipts" in actions:
        for item in evidence:
            item.witness_receipts = []
    if "below_witness_quorum" in actions:
        for item in evidence:
            item.witness_receipts = list(item.witness_receipts or [])[:1]
    if witness_receipt_limit is not None:
        for item in evidence:
            item.witness_receipts = list(item.witness_receipts or [])[:max(0, witness_receipt_limit)]
    return evidence


def _wire_payloads_for_trace(trace: Mapping[str, Any], template: CryptoTemplate) -> list[bytes]:
    payload_by_seq = {seq: raw for seq, raw in enumerate(template.wire_messages, start=1)}
    output: list[bytes] = []
    publisher_digests = {
        int(event["seq"]): str(event["digest"])
        for event in trace.get("timeline", ())
        if event.get("event") == "publisher_publish"
    }
    for delivery in sorted(
        (
            event for event in trace.get("timeline", ())
            if event.get("event") == "subscriber_delivery"
            and bool(event.get("auditor_visible", True))
        ),
        key=lambda event: int(event.get("delivery_order", 0)),
    ):
        seq = int(delivery["seq"])
        payload = payload_by_seq.get(seq)
        if payload is None:
            output.append(b"AAPA-forged-record")
            continue
        if str(delivery.get("digest")) != publisher_digests.get(seq):
            mutated = bytearray(payload)
            mutated[-1] ^= 0x01
            payload = bytes(mutated)
        output.append(payload)
    return output


def verify_real_crypto_case(
    trace: Mapping[str, Any],
    template: CryptoTemplate,
    *,
    include_registry: bool = True,
    include_latest_anchor: bool = True,
    stale_anchor: bool = False,
    witness_receipt_limit: int | None = None,
) -> dict[str, Any]:
    """Mutate and independently verify the real bundle for one trace case."""

    actions = _scenario_actions(trace)
    evidence = _mutated_evidence(
        template,
        actions,
        witness_receipt_limit=witness_receipt_limit,
    )
    registry = template.registry if include_registry else None
    anchors = None
    if evidence and template.arm_id != "A2":
        # Anchors always refer to the original complete source history.  This is
        # what makes rollback/tail omission detectable when latest is trusted.
        anchors = anchors_for_generated_evidence(
            template.evidence,
            include_latest=include_latest_anchor,
            observed_at=FIXED_AUDIT_TIME - 1,
            valid_until=(FIXED_AUDIT_TIME - 1 if stale_anchor else FIXED_AUDIT_TIME + 86_400),
            anchor_set_id=f"qos-case-{trace['case_id']}-anchors",
        )
    stream_verdict = audit_stream(
        evidence,
        template.arm_id,
        registry,
        anchors,
        audit_time=FIXED_AUDIT_TIME,
        witness_quorum=2 if template.arm_id == "A6" else None,
    ).to_dict()

    verifier = template.subscriber_verifier_factory()
    wire_results = []
    for index, payload in enumerate(_wire_payloads_for_trace(trace, template)):
        result = verifier.verify(payload)
        wire_results.append({
            "delivery_index": index,
            "valid": result.valid,
            "reason_code": result.reason_code,
            "epoch": result.envelope.epoch if result.envelope else None,
            "seq": result.envelope.seq if result.envelope else None,
        })

    bundle = bundle_to_dict(template.arm_id, evidence, bundle_id=f"qos-{trace['case_id']}") if evidence else None

    # Observed cryptographic fact: whether each presented witness receipt is
    # validly signed by the *registry-authorized* public key for its witness.
    # Validity is bound to the authorized key (not the key the receipt carries),
    # so a substituted witness key — even if self-consistently signed — is not a
    # valid trusted receipt and cannot count toward a quorum.
    witness_receipt_signatures = []
    for item in evidence or []:
        for receipt in item.witness_receipts or []:
            authorization = registry.witness_for_id(receipt.witness_id) if registry is not None else None
            authorized_key = authorization.public_key if authorization is not None else None
            scheme = authorization.signature_scheme if authorization is not None else "ML-DSA-65"
            signature_valid = bool(
                authorized_key
                and receipt.public_key == authorized_key
                and receipt.signature
                and verify_signature(authorized_key, receipt.serialize(), receipt.signature, scheme)
            )
            witness_receipt_signatures.append({
                "receipt_id": receipt.receipt_id(),
                "witness_id": receipt.witness_id,
                "public_key_hex": receipt.public_key.hex(),
                "checkpoint_anchor_hex": receipt.checkpoint_anchor.hex(),
                "signature_valid": signature_valid,
            })

    artifact_body = {
        "schema_version": CRYPTO_BRIDGE_SCHEMA_VERSION,
        "case_id": trace["case_id"],
        "arm_id": template.arm_id,
        "bundle": bundle,
        "trusted_registry": registry.to_dict() if registry is not None else None,
        "trusted_anchors": anchors.to_dict() if anchors is not None else None,
        "audit_time": FIXED_AUDIT_TIME,
        "stream_verdict": stream_verdict,
        "wire_verification": wire_results,
        "witness_receipt_signatures": witness_receipt_signatures,
    }
    artifact_id = hashlib.sha256(
        json.dumps(artifact_body, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    artifact_body["artifact_id"] = artifact_id
    return artifact_body
